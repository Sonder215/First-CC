/**
 * Get a post by its ID
 */
function getPostById(id) {
  return posts.find(p => p.id === id) || null;
}

/**
 * Get the most recent N posts
 */
function getRecentPosts(n) {
  return [...posts]
    .sort((a, b) => new Date(b.date) - new Date(a.date))
    .slice(0, n);
}

/**
 * Get all posts, optionally filtered by category
 */
function getPostsByCategory(category) {
  if (!category || category === 'all') {
    return [...posts].sort((a, b) => new Date(b.date) - new Date(a.date));
  }
  return posts
    .filter(p => p.category === category)
    .sort((a, b) => new Date(b.date) - new Date(a.date));
}

/**
 * Search posts by title (case-insensitive, both EN and ZH)
 */
function searchPosts(query) {
  const q = query.toLowerCase().trim();
  if (!q) return getPostsByCategory();
  return posts
    .filter(p =>
      p.title.toLowerCase().includes(q) ||
      p.titleZh.includes(q) ||
      p.excerpt.toLowerCase().includes(q) ||
      p.excerptZh.includes(q) ||
      p.category.includes(q)
    )
    .sort((a, b) => new Date(b.date) - new Date(a.date));
}

/**
 * Get all unique categories
 */
function getAllCategories() {
  const cats = new Set(posts.map(p => p.category));
  return ['all', ...cats];
}

